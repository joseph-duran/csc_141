places = ["Paris France", "Giza Egypt", "Sydney Australia", "Great Wall of China", "Colosseum"]
places.sort()
print(places)

print(sorted(places))
print(places)


print(sorted(places, reverse=True))
print(places)


places.sort(reverse=True)
print(places)

places.reverse()
print(places)

places.reverse()
print(places)

places.sort()
print(places)